def crossesDomains(XMLInstr, latNode):
   # whether the latency is between a general-purpose and a vector register
   def domain(idx):
      o = XMLInstr.find('./operand[@idx="%s"]' % idx)
      if (o is None) or (o.attrib.get('type') != 'reg'): return None
      return 'vec' if 'MM' in (o.text or '') else 'gpr'
   d1, d2 = domain(latNode.attrib['start_op']), domain(latNode.attrib['target_op'])
   return (d1 is not None) and (d2 is not None) and (d1 != d2)

def getAMDPerfData(arch, XMLInstr, measurementNode, loadLatency):
   iclass = XMLInstr.attrib['iclass']
   category = XMLInstr.attrib['category']
   instrString = XMLInstr.attrib['string']
   macroOps = max(1, int(measurementNode.attrib['uops']))

   memOps = [o for o in XMLInstr.iter('operand') if o.attrib.get('type') == 'mem']
   memR = any('r' in o.attrib.get('r', '') + o.attrib.get('rw', '') or o.attrib.get('r') == '1' for o in memOps)
   memW = any('w' in o.attrib.get('w', '') + o.attrib.get('rw', '') or o.attrib.get('w') == '1' for o in memOps)
   isRMW = any((o.attrib.get('r') == '1' and o.attrib.get('w') == '1') or ('r' in o.attrib.get('rw', '') and 'w' in o.attrib.get('rw', '')) for o in memOps)
   regOps = [o for o in XMLInstr.iter('operand') if o.attrib.get('type') == 'reg']
   usesVecRegs = any(('MM' in (o.text or '')) for o in regOps)
   nonSuppressedOps = [o for o in XMLInstr.iter('operand') if o.attrib.get('suppressed', '0') != '1' and o.attrib.get('type') != 'flags']

   latCycles = [int(l.attrib[a]) for l in measurementNode.iter('latency') for a in ['cycles', 'min_cycles'] if a in l.attrib]
   addrLat = [int(l.attrib['cycles_addr']) for l in measurementNode.iter('latency') if 'cycles_addr' in l.attrib]

   fpPcs = []
   ports = measurementNode.attrib.get('ports')
   if ports is not None:
      for np in ports.split('+'):
         n, p = np.split('*')
         fpPcs.extend([''.join(AMD_FP_PORTS[c] for c in p.replace('FP', ''))] * int(n))

   nLoad = int(memR)
   nStore = int(memW)
   fpStore = False
   if memW and (''.join(AMD_FP_PORTS[c] for c in '45') in fpPcs):
      # the store-data uop of a vector store; only one such uop can be executed per cycle
      fpPcs.remove(''.join(AMD_FP_PORTS[c] for c in '45'))
      fpStore = True

   # number of uops that are neither load, store, nor FP uops
   if fpPcs or fpStore:
      nALU = max(0, macroOps - len(fpPcs) - int(fpStore))
   elif not memOps:
      nALU = macroOps
   elif memR and memW:
      nALU = macroOps
   elif memR:
      isPureLoad = usesVecRegs or (category in ['DATAXFER', 'POP']) or (addrLat and min(addrLat) <= loadLatency)
      nALU = (macroOps - 1) if isPureLoad else macroOps
   else:
      isPureStore = (category in ['DATAXFER', 'PUSH'])
      nALU = (macroOps - 1) if (isPureStore or macroOps > 1) else macroOps
   if category in ['NOP', 'WIDENOP']:
      nALU = 0

   aluPorts = AMD_PORTS_FOR_ICLASS.get(iclass, AMD_PORTS_FOR_CATEGORY.get(category, AMD_ALU))
   aluPcs = ([aluPorts] + [AMD_ALU] * (nALU - 1)) if nALU else []
   if iclass in ['DIV', 'IDIV']:
      aluPcs = [aluPorts] * nALU

   portData = {}
   loadPcs = [AMD_VEC_LOAD_AGU if usesVecRegs else AMD_AGU] * nLoad
   storeAddrPcs = [AMD_RMW_STORE_ADDR if isRMW else AMD_AGU] * nStore
   for pc in loadPcs + storeAddrPcs + ([AMD_FP_STORE_DATA if (fpStore or usesVecRegs) else AMD_STORE_DATA] * nStore) + aluPcs + fpPcs:
      portData[pc] = portData.get(pc, 0) + 1

   vecIn = any(('MM' in (o.text or '')) and o.attrib.get('r') == '1' for o in regOps)
   gprOut = any(('MM' not in (o.text or '')) and o.attrib.get('w') == '1' and o.attrib.get('suppressed', '0') != '1' for o in regOps)
   if vecIn and gprOut and not memW:
      portData[AMD_ALU] = portData.get(AMD_ALU, 0) + AMD_V2G_ALU_UOPS
   perfData = {'uops': sum(portData.values()), 'retSlots': macroOps, 'uopsMITE': macroOps, 'uopsMS': 0, 'ports': portData}

   isRegMove = (('MOV' in instrString) and (not memOps) and (macroOps == 1) and (len(nonSuppressedOps) == 2) and latCycles and (max(latCycles) == 0)
                   and all(o.attrib.get('type') == 'reg' for o in nonSuppressedOps))
   # Memory renaming, measured on a Ryzen 7 7735U (microbench SET=rmw): read-modify-write instructions with a 32- or 64-bit memory operand that
   # are not microcoded (e.g., 'add dword ptr [rsi+64], ecx': 1 cycle per iteration; 16- and 8-bit forms and bts: 7 or more cycles), and
   # moves into general-purpose registers (e.g., 'mov [rsi], rax; mov rax, [rsi]; add rax, 1': 1 cycle; a vector store/load pair: 10 cycles;
   # load-op instructions are not renamed: 'mov [rsi], rax; add rax, [rsi]': 8.24 cycles).
   memWidth = int(memOps[0].attrib.get('width', 0)) if memOps else 0
   if (isRMW and memWidth in (32, 64) and macroOps <= 2 and XMLInstr.attrib.get('locked', '') != '1') or (memR and not memW and not usesVecRegs and iclass in ('MOV', 'MOVZX', 'MOVSX', 'MOVSXD', 'POP')):
      perfData['memRename'] = 1
   if isRegMove:
      # eliminated at rename; the '_SR' variants are used if the move cannot be eliminated (see instructions.py)
      perfData.update({'uops': 0, 'ports': {}, 'uops_SR': 1, 'ports_SR': portData})

   TPs = [float(measurementNode.attrib[a]) for a in ['TP_unrolled', 'TP_loop'] if a in measurementNode.attrib]
   if 'div_cycles' in measurementNode.attrib:
      # as for the Intel CPUs (see main())
      divCycles = int(measurementNode.attrib['div_cycles'])
      TP = int(float(measurementNode.attrib.get('TP_unrolled', divCycles)))
      if TP <= divCycles:
         perfData['divC'] = TP
      else:
         perfData['divC'] = divCycles
         perfData['TP'] = TP
   elif TPs and (category not in ['COND_BR', 'UNCOND_BR', 'CALL', 'RET']):
      # Instructions whose measured throughput is much lower than what the ports and the dispatch width allow: microcoded instructions,
      # instructions with a lock prefix, FP division and square root (there is no model of the microcode sequencer or the FP divider).
      # As for some instructions on Intel CPUs, the measured throughput is then used as a limit for this instruction.
      pcs = list(portData.items())
      bound = macroOps / 6.0
      for mask in range(1, 1 << len(pcs)):
         union = set(p for i, (pc, _) in enumerate(pcs) if mask & (1 << i) for p in pc)
         bound = max(bound, sum(n for pc, n in pcs if set(pc) <= union) / float(len(union)))
      locked = (XMLInstr.attrib.get('locked', '') == '1')
      if (min(TPs) > 1.3 * bound) and ((min(TPs) >= 1.0) or locked or (macroOps >= 2)):
         perfData['TP'] = round(min(TPs), 2)
         amdStats[arch]['measured throughput used as a limit'] += 1

   # statistics, and comparison with the measured throughput for instructions with one uop
   s = amdStats[arch]
   s['instructions'] += 1
   s['FP ports from uops.info' if (fpPcs or fpStore) else ('synthesized (table)' if aluPorts != AMD_ALU else 'synthesized (default ALU)') if nALU
     else 'load/store/eliminated only'] += 1
   if TPs and (not memOps) and (len(aluPcs) == 1) and (not fpPcs) and (category not in ['COND_BR', 'UNCOND_BR', 'CALL', 'RET']):
      s['single-uop ALU instr. with measured TP'] += 1
      if abs(min(TPs) - 1.0/len(aluPorts)) > 0.13:
         s['... of which measured TP disagrees with port group size'] += 1
         amdTPMismatches[arch].append((instrString, min(TPs), aluPorts))
   return perfData


