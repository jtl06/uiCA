#!/usr/bin/env python3

import argparse
import os
import shutil
import xml.etree.ElementTree as ET
from collections import defaultdict

from microArchConfigs import MicroArchConfigs
try:
   from xedIformMap import xedIformMap # generated by genIformMap.py
except ImportError:
   xedIformMap = {}

allXmlAttributes = ['agen', 'bcast', 'eosz', 'high8', 'immzero', 'mask', 'rep', 'rm', 'sae', 'zeroing']

# Experimental AMD support.
# uops.info has no port data for integer instructions on AMD CPUs (there are no suitable performance counters), and its uop counts are in
# macro-ops. We therefore synthesize the uops: load/store uops are derived from the operands, FP uops are taken from uops.info, and the
# remaining uops are assigned to a group of ALUs according to the tables below. The tables follow LLVM's X86ScheduleZnver3.td, which is based on
# AMD's Software Optimization Guide for Family 19h (section 2.10.2).
AMD_ALU = 'abcd'       # ALU0-3
AMD_AGU = 'ghi'        # AGU0-2
AMD_VEC_LOAD_AGU = 'gh' # only two vector loads can be executed per cycle (e.g., uops.info: MOVAPD (XMM, M128) has a throughput of 0.5)
# A read-modify-write instruction computes its address only once (e.g., uops.info: INC (M64) has a throughput of 0.5, which is the limit for
# stores). Its store-address uop is therefore assigned to virtual ports that do not correspond to execution units.
AMD_RMW_STORE_ADDR = 'yz'
AMD_STORE_DATA = 'st'  # integer store data; two stores per cycle
AMD_FP_STORE_DATA = 'x'
AMD_FP_PORTS = {'0': 'k', '1': 'l', '2': 'm', '3': 'n', '4': 'o', '5': 'p'}
# Branches: the second branch unit (BRU1) is attached to the scheduler of ALU3. Measurements on a Ryzen 7 7735U show that it does not add
# capacity (K independent adds + dec/jnz run at (K+1)/4 cycles per iteration, 3x test/jnz + dec/jnz at 2), so branches are modeled as uops
# for ALU0 or ALU3.
AMD_PORTS_FOR_CATEGORY = {'COND_BR': 'ad', 'UNCOND_BR': 'ad', 'CALL': 'ad', 'RET': 'ad',
                          'SHIFT': 'bc', 'ROTATE': 'bc', 'CMOV': 'ad', 'SETCC': 'ad'}
AMD_PORTS_FOR_ICLASS = {'IMUL': 'b', 'MUL': 'b', 'MULX': 'b', 'DIV': 'a', 'IDIV': 'a', 'BSF': 'b', 'BSR': 'b', 'PDEP': 'b', 'PEXT': 'b', 'CRC32': 'b',
                        'BT': 'bc', 'BTC': 'bc', 'BTR': 'bc', 'BTS': 'bc', 'BEXTR': 'bc', 'BZHI': 'bc', 'TZCNT': 'bc', 'SHLD': 'bc', 'SHRD': 'bc',
                        'SARX': 'bc', 'SHLX': 'bc', 'SHRX': 'bc', 'RORX': 'bc', 'LAHF': 'd'}
# Measured on a Ryzen 7 7735U (Zen 3+): the register/immediate forms of these instructions are fused with a subsequent jnz. We assume that
# this holds for all conditional jumps; forms with memory operands were not measured and are treated as not fusible.
AMD_MACRO_FUSIBLE_ICLASSES = ['CMP', 'TEST', 'ADD', 'SUB', 'AND', 'OR', 'XOR', 'INC', 'DEC']
amdStats = defaultdict(lambda: defaultdict(int))
amdTPMismatches = defaultdict(list)

AMD_CROSS_DOMAIN_BOUND_CORRECTION = 2

def crossesDomains(XMLInstr, latNode):
   # whether the latency is between a general-purpose and a vector register
   def domain(idx):
      o = XMLInstr.find('./operand[@idx="%s"]' % idx)
      if (o is None) or (o.attrib.get('type') != 'reg'): return None
      return 'vec' if 'MM' in (o.text or '') else 'gpr'
   d1, d2 = domain(latNode.attrib['start_op']), domain(latNode.attrib['target_op'])
   return (d1 is not None) and (d2 is not None) and (d1 != d2)

def getAMDPerfData(arch, XMLInstr, measurementNode, loadLatency):
   iclass = XMLInstr.attrib['iclass']
   category = XMLInstr.attrib['category']
   instrString = XMLInstr.attrib['string']
   macroOps = max(1, int(measurementNode.attrib['uops']))

   memOps = [o for o in XMLInstr.iter('operand') if o.attrib.get('type') == 'mem']
   memR = any('r' in o.attrib.get('r', '') + o.attrib.get('rw', '') or o.attrib.get('r') == '1' for o in memOps)
   memW = any('w' in o.attrib.get('w', '') + o.attrib.get('rw', '') or o.attrib.get('w') == '1' for o in memOps)
   isRMW = any((o.attrib.get('r') == '1' and o.attrib.get('w') == '1') or ('r' in o.attrib.get('rw', '') and 'w' in o.attrib.get('rw', '')) for o in memOps)
   regOps = [o for o in XMLInstr.iter('operand') if o.attrib.get('type') == 'reg']
   usesVecRegs = any(('MM' in (o.text or '')) for o in regOps)
   nonSuppressedOps = [o for o in XMLInstr.iter('operand') if o.attrib.get('suppressed', '0') != '1' and o.attrib.get('type') != 'flags']

   latCycles = [int(l.attrib[a]) for l in measurementNode.iter('latency') for a in ['cycles', 'min_cycles'] if a in l.attrib]
   addrLat = [int(l.attrib['cycles_addr']) for l in measurementNode.iter('latency') if 'cycles_addr' in l.attrib]

   fpPcs = []
   ports = measurementNode.attrib.get('ports')
   if ports is not None:
      for np in ports.split('+'):
         n, p = np.split('*')
         fpPcs.extend([''.join(AMD_FP_PORTS[c] for c in p.replace('FP', ''))] * int(n))

   nLoad = int(memR)
   nStore = int(memW)
   fpStore = False
   if memW and (''.join(AMD_FP_PORTS[c] for c in '45') in fpPcs):
      # the store-data uop of a vector store; only one such uop can be executed per cycle
      fpPcs.remove(''.join(AMD_FP_PORTS[c] for c in '45'))
      fpStore = True

   # number of uops that are neither load, store, nor FP uops
   if fpPcs or fpStore:
      nALU = max(0, macroOps - len(fpPcs) - int(fpStore))
   elif not memOps:
      nALU = macroOps
   elif memR and memW:
      nALU = macroOps
   elif memR:
      isPureLoad = usesVecRegs or (category in ['DATAXFER', 'POP']) or (addrLat and min(addrLat) <= loadLatency)
      nALU = (macroOps - 1) if isPureLoad else macroOps
   else:
      isPureStore = (category in ['DATAXFER', 'PUSH'])
      nALU = (macroOps - 1) if (isPureStore or macroOps > 1) else macroOps
   if category in ['NOP', 'WIDENOP']:
      nALU = 0

   aluPorts = AMD_PORTS_FOR_ICLASS.get(iclass, AMD_PORTS_FOR_CATEGORY.get(category, AMD_ALU))
   aluPcs = ([aluPorts] + [AMD_ALU] * (nALU - 1)) if nALU else []
   if iclass in ['DIV', 'IDIV']:
      aluPcs = [aluPorts] * nALU

   portData = {}
   loadPcs = [AMD_VEC_LOAD_AGU if usesVecRegs else AMD_AGU] * nLoad
   storeAddrPcs = [AMD_RMW_STORE_ADDR if isRMW else AMD_AGU] * nStore
   for pc in loadPcs + storeAddrPcs + ([AMD_FP_STORE_DATA if (fpStore or usesVecRegs) else AMD_STORE_DATA] * nStore) + aluPcs + fpPcs:
      portData[pc] = portData.get(pc, 0) + 1

   perfData = {'uops': sum(portData.values()), 'retSlots': macroOps, 'uopsMITE': macroOps, 'uopsMS': 0, 'ports': portData}

   isRegMove = (('MOV' in instrString) and (not memOps) and (macroOps == 1) and (len(nonSuppressedOps) == 2) and latCycles and (max(latCycles) == 0)
                   and all(o.attrib.get('type') == 'reg' for o in nonSuppressedOps))
   # Memory renaming, measured on a Ryzen 7 7735U (microbench SET=rmw): read-modify-write instructions with a 32- or 64-bit memory operand that
   # are not microcoded (e.g., 'add dword ptr [rsi+64], ecx': 1 cycle per iteration; 16- and 8-bit forms and bts: 7 or more cycles), and
   # moves into general-purpose registers (e.g., 'mov [rsi], rax; mov rax, [rsi]; add rax, 1': 1 cycle; a vector store/load pair: 10 cycles;
   # load-op instructions are not renamed: 'mov [rsi], rax; add rax, [rsi]': 8.24 cycles).
   memWidth = int(memOps[0].attrib.get('width', 0)) if memOps else 0
   if (isRMW and memWidth in (32, 64) and macroOps <= 2 and XMLInstr.attrib.get('locked', '') != '1') or (memR and not memW and not usesVecRegs and iclass in ('MOV', 'MOVZX', 'MOVSX', 'MOVSXD', 'POP')):
      perfData['memRename'] = 1
   if isRegMove:
      # eliminated at rename; the '_SR' variants are used if the move cannot be eliminated (see instructions.py)
      perfData.update({'uops': 0, 'ports': {}, 'uops_SR': 1, 'ports_SR': portData})

   TPs = [float(measurementNode.attrib[a]) for a in ['TP_unrolled', 'TP_loop'] if a in measurementNode.attrib]
   if 'div_cycles' in measurementNode.attrib:
      # as for the Intel CPUs (see main())
      divCycles = int(measurementNode.attrib['div_cycles'])
      TP = int(float(measurementNode.attrib.get('TP_unrolled', divCycles)))
      if TP <= divCycles:
         perfData['divC'] = TP
      else:
         perfData['divC'] = divCycles
         perfData['TP'] = TP
   elif TPs and (category not in ['COND_BR', 'UNCOND_BR', 'CALL', 'RET']):
      # Instructions whose measured throughput is much lower than what the ports and the dispatch width allow: microcoded instructions,
      # instructions with a lock prefix, FP division and square root (there is no model of the microcode sequencer or the FP divider).
      # As for some instructions on Intel CPUs, the measured throughput is then used as a limit for this instruction.
      pcs = list(portData.items())
      bound = macroOps / 6.0
      for mask in range(1, 1 << len(pcs)):
         union = set(p for i, (pc, _) in enumerate(pcs) if mask & (1 << i) for p in pc)
         bound = max(bound, sum(n for pc, n in pcs if set(pc) <= union) / float(len(union)))
      locked = (XMLInstr.attrib.get('locked', '') == '1')
      if (min(TPs) > 1.3 * bound) and ((min(TPs) >= 1.0) or locked or (macroOps >= 2)):
         perfData['TP'] = round(min(TPs), 2)
         amdStats[arch]['measured throughput used as a limit'] += 1

   # statistics, and comparison with the measured throughput for instructions with one uop
   s = amdStats[arch]
   s['instructions'] += 1
   s['FP ports from uops.info' if (fpPcs or fpStore) else ('synthesized (table)' if aluPorts != AMD_ALU else 'synthesized (default ALU)') if nALU
     else 'load/store/eliminated only'] += 1
   if TPs and (not memOps) and (len(aluPcs) == 1) and (not fpPcs) and (category not in ['COND_BR', 'UNCOND_BR', 'CALL', 'RET']):
      s['single-uop ALU instr. with measured TP'] += 1
      if abs(min(TPs) - 1.0/len(aluPorts)) > 0.13:
         s['... of which measured TP disagrees with port group size'] += 1
         amdTPMismatches[arch].append((instrString, min(TPs), aluPorts))
   return perfData


def main():
   parser = argparse.ArgumentParser(description='Convert XML file')
   parser.add_argument('xmlfile', help="XML file")
   args = parser.parse_args()

   root = ET.parse(args.xmlfile)
   instrDataForArch = defaultdict(dict)
   perfDataForArch = defaultdict(list)
   perfDataForArchIdxDict = defaultdict(dict)
   attrDataForArch = defaultdict(list)
   attrDataForArchIdxDict = defaultdict(dict)
   condJumps = set(XMLInstr.attrib['string'] for XMLInstr in root.iter('instruction')
                      if XMLInstr.attrib['category'] == 'COND_BR' and XMLInstr.attrib['iclass'].startswith('J') and 'CXZ' not in XMLInstr.attrib['iclass'])
   for XMLInstr in root.iter('instruction'):
      iform = XMLInstr.attrib['iform']
      instrString = XMLInstr.attrib['string']
      attr = {a: XMLInstr.attrib[a] for a in allXmlAttributes if a in XMLInstr.attrib}
      if iform in xedIformMap:
         # newer uops.info XML files use iform names from newer XED versions; use the names of the XED version bundled with uiCA
         iform, eosz = xedIformMap[iform]
         if eosz and ('eosz' not in attr):
            attr['eosz'] = eosz
      opIdxToName = {o.attrib['idx']:o.attrib['name'] for o in XMLInstr.iter('operand') if 'name' in o.attrib}

      flagNode = XMLInstr.find('./operand[@type="flags"]')
      readFlags = set()
      writtenFlags = set()
      if flagNode is not None:
         for flag in ['A', 'C', 'O', 'P', 'S', 'Z']:
            rw = flagNode.attrib.get('flag_' + flag + 'F', '')
            if ('r' in rw) or ('cw' in rw):
               readFlags.add(flag)
            if 'w' in rw:
               writtenFlags.add(flag)

      for archNode in XMLInstr.iter('architecture'):
         if archNode.attrib['name'] not in MicroArchConfigs:
            continue
         measurementNode = archNode.find('./measurement')
         if measurementNode is not None:
            instrData = dict()
            if iform not in instrDataForArch[archNode.attrib['name']]:
               instrDataForArch[archNode.attrib['name']][iform] = []
            instrDataForArch[archNode.attrib['name']][iform].append(instrData)

            attrRepr = repr(attr)
            curAttrDataForArch = attrDataForArch[archNode.attrib['name']]
            curAttrDataForArchIdxDict = attrDataForArchIdxDict[archNode.attrib['name']]
            if attrRepr not in curAttrDataForArchIdxDict:
               curAttrDataForArchIdxDict[attrRepr] = len(curAttrDataForArch)
               curAttrDataForArch.append(attr)
            instrData['attr'] = curAttrDataForArchIdxDict[attrRepr]

            instrData['string'] = instrString
            if XMLInstr.attrib.get('locked', '') == '1':
               instrData['locked'] = 1

            if readFlags:
               instrData['flagsR'] = readFlags
            if writtenFlags:
               instrData['flagsW'] = writtenFlags

            perfData = {}
            isAMD = MicroArchConfigs[archNode.attrib['name']].isAMD
            if isAMD:
               perfData = getAMDPerfData(archNode.attrib['name'], XMLInstr, measurementNode, MicroArchConfigs[archNode.attrib['name']].loadLatency)
            for mSuffix, iSuffix in ([] if isAMD else [('', ''), ('_same_reg', '_SR'), ('_indexed', '_I')]):
               for mKey, iKey in [('uops', 'uops'), ('uops_retire_slots', 'retSlots'), ('uops_MITE', 'uopsMITE'), ('uops_MS', 'uopsMS'),
                                  ('div_cycles', 'divC'), ('complex_decoder', 'complDec'), ('available_simple_decoders', 'sDec')]:
                  if mKey == 'div_cycles' and mKey+mSuffix in measurementNode.attrib:
                     divCycles = int(measurementNode.attrib.get(mKey+mSuffix))
                     TP = int(float(measurementNode.attrib.get('TP_unrolled'+mSuffix, divCycles)))
                     if TP <= divCycles:
                        perfData[iKey+iSuffix] = TP # on some CPUs, the dividers are partially pipelined
                     else:
                        perfData[iKey+iSuffix] = divCycles
                        perfData['TP'+iSuffix] = TP
                  else:
                     mValue = measurementNode.attrib.get(mKey+mSuffix)
                     if mValue is not None:
                        intValue = int(mValue)
                        if mKey in ['uops_retire_slots', 'uops_MITE']:
                           intValue = max(1, intValue)
                        perfData[iKey+iSuffix] = intValue
               if instrString in ['CPUID', 'MFENCE', 'PAUSE', 'RDTSC'] or XMLInstr.attrib.get('locked', '') == '1':
                  TP_loop = measurementNode.attrib.get('TP_loop'+mSuffix)
                  TP_unrolled = measurementNode.attrib.get('TP_unrolled'+mSuffix)
                  TPs = [int(float(tp)) for tp in [TP_loop, TP_unrolled] if tp is not None]
                  if TPs:
                     perfData['TP'+iSuffix] = min(TPs)

               if (mSuffix == '') and perfData.get('uopsMS') and (measurementNode.attrib.get('ports') is not None):
                  # Microcoded instructions whose measured throughput is much lower than what the ports and the issue width allow (e.g.,
                  # AESKEYGENASSIST: 13 cycles on ADL-P, but ~4 cycles from its ports): stored separately, used only by the experimental
                  # configurations (see instructions.py), so that the stock models are unchanged
                  TPs = [float(measurementNode.attrib[a]) for a in ['TP_unrolled', 'TP_loop'] if a in measurementNode.attrib]
                  pcs = [(p.replace('p', ''), int(n)) for np in measurementNode.attrib['ports'].split('+') for n, p in [np.split('*')]]
                  bound = perfData.get('uops', 0) / 5.0
                  for mask in range(1, 1 << len(pcs)):
                     union = set(c for i, (pc, _) in enumerate(pcs) if mask & (1 << i) for c in pc)
                     bound = max(bound, sum(n for pc, n in pcs if set(pc) <= union) / float(len(union)))
                  if TPs and (min(TPs) >= 1.0) and (min(TPs) > 1.3 * bound) and (XMLInstr.attrib['category'] not in ['COND_BR', 'UNCOND_BR', 'CALL', 'RET']):
                     perfData['TP_MS'] = round(min(TPs), 2)

               ports = measurementNode.attrib.get('ports'+mSuffix)
               if ports is not None: # ToDo: AMD
                  if (archNode.attrib['name'] not in ['ICL', 'TGL', 'RKL', 'ADL-P']) and (XMLInstr.attrib['category'] == 'COND_BR') and (ports == '1*p06'):
                     ports = '1*p6' # taken branches can only use port 6
                  perfData['ports'+iSuffix] = {p.replace('p', ''): int(n) for np in ports.split('+') for n, p in [np.split('*')]}
                  if ((iSuffix == '_I') and (archNode.attrib['name'] == 'ADL-P') and perfData.get('ports')
                        and (sum(perfData['ports_I'].values()) < sum(perfData['ports'].values()))):
                     # uops.info's port counts for indexed memory operands on Alder Lake-P lack the non-memory uops of about 3200 instruction
                     # forms (e.g., VADDPD (XMM, XMM, M128): uops_indexed="2", ports_indexed="1*p23A"; ADD (R64, M64): 1*p23A); the ports of
                     # the non-indexed form are used instead
                     perfData['ports_I'] = perfData['ports']
               elif perfData.get('uops'+iSuffix, -1) == 0:
                  perfData['ports'+iSuffix] = {}

            macroFusible = measurementNode.attrib.get('macro_fusible')
            if macroFusible is not None:
               instrData['macroFusible'] = set(macroFusible.split(';'))
            if (isAMD and (XMLInstr.attrib['iclass'] in AMD_MACRO_FUSIBLE_ICLASSES)
                  and not any(o.attrib.get('type') == 'mem' for o in XMLInstr.iter('operand'))):
               instrData['macroFusible'] = condJumps

            latData = dict()
            latDataSameReg = dict()

            for latNode in measurementNode.iter('latency'):
               startOp = opIdxToName[latNode.attrib['start_op']]
               targetOp = opIdxToName[latNode.attrib['target_op']]
               if 'cycles' in latNode.attrib:
                  latData[(startOp, targetOp)] = int(latNode.attrib['cycles'])
                  if isAMD and latNode.attrib.get('cycles_is_upper_bound') == '1' and crossesDomains(XMLInstr, latNode):
                     # uops.info measures the latency of moves between general-purpose and vector registers in a chain with a move in the
                     # other direction and attributes almost all of it to this instruction; perf, Ryzen 7 7735U: 'vmovq xmm0, rax;
                     # vmovq rax, xmm0': 6 cycles per iteration, upper bounds 5 + 5 (microbench SET=v2g: all round trips are 4 cycles shorter)
                     latData[(startOp, targetOp)] = max(1, latData[(startOp, targetOp)] - AMD_CROSS_DOMAIN_BOUND_CORRECTION)
               if 'cycles_same_reg' in latNode.attrib:
                  latDataSameReg[(startOp, targetOp)] = int(latNode.attrib['cycles_same_reg'])
               if 'min_cycles' in latNode.attrib:
                  latData[(startOp, targetOp)] = int(latNode.attrib['min_cycles'])
               if 'cycles_addr' in latNode.attrib:
                  latData[(startOp, targetOp, 'addr')] = int(latNode.attrib['cycles_addr'])
               if 'cycles_addr_index' in latNode.attrib:
                  latData[(startOp, targetOp, 'addrI')] = int(latNode.attrib['cycles_addr_index'])
               if 'cycles_mem' in latNode.attrib:
                  latData[(startOp, targetOp, 'mem')] = int(latNode.attrib['cycles_mem'])
               # instructions with a value-dependent latency (e.g., division, square root) only have min_ and max_ variants; without these, the
               # latency of the memory operands would be 1 (e.g., 'divpd xmm5, [rax]' would not be limited by the latency of xmm5 -> xmm5)
               for suffix, key in [('addr', 'addr'), ('addr_index', 'addrI'), ('mem', 'mem')]:
                  if ('min_cycles_' + suffix in latNode.attrib) and ('cycles_' + suffix not in latNode.attrib):
                     latData[(startOp, targetOp, key)] = int(latNode.attrib['min_cycles_' + suffix])

            if latData:
               perfData['lat'] = latData
            if latDataSameReg:
               perfData['lat_SR'] = latDataSameReg

            perfRepr = repr(perfData)
            curPerfDataForArch = perfDataForArch[archNode.attrib['name']]
            curPerfDataForArchIdxDict = perfDataForArchIdxDict[archNode.attrib['name']]
            if perfRepr not in curPerfDataForArchIdxDict:
               curPerfDataForArchIdxDict[perfRepr] = len(curPerfDataForArch)
               curPerfDataForArch.append(perfData)
            instrData['perfData'] = curPerfDataForArchIdxDict[perfRepr]

   path = 'instrData'

   try:
      os.makedirs(path)
   except OSError:
      if not os.path.isdir(path):
         raise

   open(os.path.join(path, '__init__.py'), 'a').close()

   for arch in instrDataForArch.keys():
      with open(os.path.join(path, arch + '_data.py'), 'w') as f:
         f.write('instrData = ' + repr(instrDataForArch[arch]) + '\n')
         f.write('perfData = ' + repr(perfDataForArch[arch]) + '\n')
         f.write('attrData = ' + repr(attrDataForArch[arch]) + '\n')

   for name, cfg in MicroArchConfigs.items():
      if cfg.dataFrom and (cfg.dataFrom in instrDataForArch):
         # e.g., ICX uses the data of RKL
         shutil.copyfile(os.path.join(path, cfg.dataFrom + '_data.py'), os.path.join(path, name + '_data.py'))
         instrDataForArch[name] = instrDataForArch[cfg.dataFrom]
         perfDataForArch[name] = perfDataForArch[cfg.dataFrom]

   allPorts = {}
   ALUPorts = {}
   for arch in instrDataForArch.keys():
      allPorts[arch] = sorted({p for pd in perfDataForArch[arch] for pc in pd.get('ports', {}).keys() for p in pc})
      ALUPorts[arch] = sorted(next(iter(perfDataForArch[arch][instrDataForArch[arch]['AND_GPRv_IMMb'][0]['perfData']]['ports'].keys())))
   with open(os.path.join(path, 'uArchInfo.py'), 'w') as f:
      f.write('allPorts = ' + repr(allPorts) + '\n')
      f.write('ALUPorts = ' + repr(ALUPorts) + '\n')


   for arch in sorted(amdStats):
      print(arch + ' (experimental):')
      for k, v in amdStats[arch].items():
         print('   {}: {}'.format(k, v))
      with open(os.path.join(path, arch + '_TP_mismatches.txt'), 'w') as f:
         for instrString, TP, ports in sorted(amdTPMismatches[arch]):
            f.write('{}\tmeasured TP: {}\tassigned ports: {}\n'.format(instrString, TP, ports))


if __name__ == "__main__":
    main()
