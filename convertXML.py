def applyInstrCorrections(arch, instrString, perfData):
   c = INSTR_CORRECTIONS.get(arch, {}).get(instrString)
   if not c:
      return perfData
   perfData = dict(perfData)
   for k in ('TP', 'TP_MS', 'divC'):
      if k in c:
         perfData[k] = c[k]
   if c.get('lat'):
      perfData['lat'] = dict(perfData.get('lat', {}))
      perfData['lat'].update(c['lat'])
   return perfData

